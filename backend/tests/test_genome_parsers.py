class TestParseLine:
    """单行解析"""

    def test_parse_line_23andme(self, parser):
        """23andMe 行解析"""
        result = parser._parse_line("rs1234\t1\t100000\tAA", "23andme")
        assert result == ("rs1234", "1", "AA")

    def test_parse_line_ancestry(self, parser):
        """Ancestry 行解析（allele1+allele2 拼接）"""
        result = parser._parse_line("rs1234\t1\t100000\tA\tA", "ancestry")
        assert result == ("rs1234", "1", "AA")

    def test_parse_line_wechat(self, parser):
        """微信基因行解析"""
        result = parser._parse_line("rs1234\t1\t100000\tAA", "wechat_gene")
        assert result == ("rs1234", "1", "AA")

    def test_parse_line_generic(self, parser):
        """通用格式行解析"""
        result = parser._parse_line("rs1234,AA", "generic")
        assert result == ("rs1234", "", "AA")

    def test_parse_line_invalid(self, parser):
        """无效行返回 None"""
        assert parser._parse_line("invalid", "23andme") is None
        assert parser._parse_line("", "generic") is None

    def test_parse_line_ancestry_missing_allele(self, parser):
        """Ancestry 缺失等位 → '--'"""
        result = parser._parse_line("rs1234\t1\t100000\t\t\t", "ancestry")
        assert result is not None
        assert result[2] == "--"



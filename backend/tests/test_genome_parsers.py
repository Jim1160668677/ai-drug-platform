class TestSnpChipParser:
    """parse() 集成测试"""

    @pytest.mark.asyncio
    async def test_parse_23andme(self, parser, sample_23andme):
        """解析 23andMe 格式"""
        dataset = SimpleNamespace(storage_path=sample_23andme)
        result = await parser.parse(dataset)
        assert result["summary"]["total_variants"] == 4
        assert result["summary"]["source_format"] == "23andme"
        assert result["quality_metrics"]["parseable"] is True
        assert result["quality_metrics"]["missing_rate"] == 0.0
        # genotype_sample 保留前 5 条
        sample = result["summary"]["genotype_sample"]
        assert "rs1234" in sample

    @pytest.mark.asyncio
    async def test_parse_ancestry(self, parser, sample_ancestry):
        """解析 Ancestry 格式"""
        dataset = SimpleNamespace(storage_path=sample_ancestry)
        result = await parser.parse(dataset)
        assert result["summary"]["total_variants"] == 3
        assert result["summary"]["source_format"] == "ancestry"
        # Ancestry 应拼接 allele1+allele2
        sample = result["summary"]["genotype_sample"]
        assert sample["rs1234"] == "AA"

    @pytest.mark.asyncio
    async def test_parse_wechat(self, parser, sample_wechat):
        """解析微信基因格式"""
        dataset = SimpleNamespace(storage_path=sample_wechat)
        result = await parser.parse(dataset)
        assert result["summary"]["total_variants"] == 2
        assert result["summary"]["source_format"] == "wechat_gene"

    @pytest.mark.asyncio
    async def test_parse_generic(self, parser, sample_generic):
        """解析通用格式"""
        dataset = SimpleNamespace(storage_path=sample_generic)
        result = await parser.parse(dataset)
        assert result["summary"]["total_variants"] == 3
        assert result["summary"]["source_format"] == "generic"

    @pytest.mark.asyncio
    async def test_parse_with_missing(self, parser, sample_with_missing):
        """含缺失基因型 → missing_rate > 0"""
        dataset = SimpleNamespace(storage_path=sample_with_missing)
        result = await parser.parse(dataset)
        assert result["summary"]["total_variants"] == 4
        assert result["quality_metrics"]["missing_rate"] == 0.5  # 2/4
        assert result["quality_metrics"]["non_missing_count"] == 2

    @pytest.mark.asyncio
    async def test_parse_file_not_found(self, parser, tmp_path):
        """文件不存在"""
        path = str(tmp_path / "not_exist.txt")
        dataset = SimpleNamespace(storage_path=path)
        result = await parser.parse(dataset)
        assert "error" in result["summary"]
        assert "文件不存在" in result["summary"]["error"]

    @pytest.mark.asyncio
    async def test_parse_empty_file(self, parser, sample_empty):
        """空文件 → 无有效记录"""
        dataset = SimpleNamespace(storage_path=sample_empty)
        result = await parser.parse(dataset)
        assert "error" in result["summary"]
        assert "无有效基因型记录" in result["summary"]["error"]

    @pytest.mark.asyncio
    async def test_parse_by_chrom_counter(self, parser, sample_23andme):
        """by_chrom 统计"""
        dataset = SimpleNamespace(storage_path=sample_23andme)
        result = await parser.parse(dataset)
        by_chrom = result["summary"]["by_chrom"]
        assert by_chrom.get("1") == 1
        assert by_chrom.get("5") == 1
        assert by_chrom.get("11") == 1
        assert by_chrom.get("3") == 1

    @pytest.mark.asyncio
    async def test_parse_no_storage_path(self, parser):
        """storage_path 为 None"""
        dataset = SimpleNamespace(storage_path=None)
        result = await parser.parse(dataset)
        assert "error" in result["summary"]

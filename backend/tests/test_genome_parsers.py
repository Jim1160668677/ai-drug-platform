class TestDetectFormat:
    """格式自动识别"""

    def test_detect_23andme(self, parser):
        """23andMe 头部特征"""
        head = ["# This data file generated by 23andMe\n"]
        assert parser._detect_format(head) == "23andme"

    def test_detect_ancestry_by_header(self, parser):
        """Ancestry 头部特征"""
        head = ["# AncestryDNA raw data\n"]
        assert parser._detect_format(head) == "ancestry"

    def test_detect_wechat(self, parser):
        """微信基因头部特征"""
        head = ["# 微基因检测报告\n"]
        assert parser._detect_format(head) == "wechat_gene"

    def test_detect_by_column_count_5(self, parser):
        """按列数推断 ancestry（5 列）"""
        head = ["rsid\tchromosome\tposition\tallele1\tallele2\n"]
        assert parser._detect_format(head) == "ancestry"

    def test_detect_by_column_count_4(self, parser):
        """按列数推断 23andme（4 列）"""
        head = ["rs1234\t1\t100000\tAA\n"]
        assert parser._detect_format(head) == "23andme"

    def test_detect_by_column_count_2(self, parser):
        """按列数推断 generic（2 列）"""
        head = ["rs1234,AA\n"]
        assert parser._detect_format(head) == "generic"

    def test_detect_empty_head(self, parser):
        """空头部默认 generic"""
        head = []
        assert parser._detect_format(head) == "generic"


